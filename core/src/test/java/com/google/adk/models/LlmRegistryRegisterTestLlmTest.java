  @Test
  @Order(13)
  @Tag("integration")
  @DisplayName(
      "Scenario 13: Concurrent registration and cache population does not cause concurrent modification errors")
  public void testConcurrentRegistrationDoesNotThrowAndEndsInConsistentState()
      throws InterruptedException {
    Map<String, BaseLlm> aMap = new ConcurrentHashMap<>();
    BaseLlm aInst = Mockito.mock(BaseLlm.class);
    aMap.put("custom-1", aInst);
    LlmFactory aFactory = factoryFromMap(aMap);
    LlmRegistry.registerTestLlm("custom-.*", aFactory);
    BaseLlm initial = LlmRegistry.getLlm("custom-1");
    Map<String, BaseLlm> bMap = new ConcurrentHashMap<>();
    BaseLlm bInst = Mockito.mock(BaseLlm.class);
    bMap.put("custom-1", bInst);
    LlmFactory bFactory = factoryFromMap(bMap);
    CountDownLatch startLatch = new CountDownLatch(1);
    CountDownLatch doneLatch = new CountDownLatch(2);
    AtomicReference<Throwable> errorRef = new AtomicReference<>(null);
    ExecutorService pool = Executors.newFixedThreadPool(2);
    pool.submit(
        () -> {
          try {
            startLatch.await(5, TimeUnit.SECONDS);
            for (int i = 0; i < 1000; i++) {
              BaseLlm x = LlmRegistry.getLlm("custom-1");
              if (x == null) {
                throw new AssertionError("Instance should not be null");
              }
            }
          } catch (Throwable t) {
            errorRef.compareAndSet(null, t);
          } finally {
            doneLatch.countDown();
          }
        });
    pool.submit(
        () -> {
          try {
            startLatch.await(5, TimeUnit.SECONDS);
            LlmRegistry.registerTestLlm("custom-.*", bFactory);
          } catch (Throwable t) {
            errorRef.compareAndSet(null, t);
          } finally {
            doneLatch.countDown();
          }
        });
    startLatch.countDown();
    doneLatch.await(10, TimeUnit.SECONDS);
    pool.shutdownNow();
    if (errorRef.get() != null) {
      throw new AssertionError("Unexpected error in concurrent operations", errorRef.get());
    }
    BaseLlm finalInst = LlmRegistry.getLlm("custom-1");
    assertNotSame((BaseLlm) initial, (BaseLlm) finalInst);
    assertSame((BaseLlm) bInst, (BaseLlm) finalInst);
  }

