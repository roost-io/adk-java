  @Test
  @Tag("integration")
  @Timeout(10)
  public void testConcurrentRegistrationDoesNotThrowAndEndsInConsistentState() throws Exception {
    String pattern = "conc-.*";
    String model = "conc-1";
    CountingFactory initialFactory = new CountingFactory();
    CountingFactory secondFactory = new CountingFactory();
    LlmRegistry.registerTestLlm(pattern, initialFactory);
    CyclicBarrier barrier = new CyclicBarrier(2);
    CountDownLatch done = new CountDownLatch(2);
    AtomicReference<Throwable> errorRef = new AtomicReference<>(null);
    Thread t1 =
        new Thread(
            () -> {
              try {
                barrier.await();
                // Repeatedly get LLM to exercise concurrent behavior
                for (int i = 0; i < 1000; i++) {
                  BaseLlm l = (BaseLlm) LlmRegistry.getLlm(model);
                  assertNotNull((BaseLlm) l);
                }
              } catch (Throwable t) {
                errorRef.set(t);
              } finally {
                done.countDown();
              }
            });
    Thread t2 =
        new Thread(
            () -> {
              try {
                barrier.await();
                // Register replacement factory concurrently
                LlmRegistry.registerTestLlm(pattern, secondFactory);
              } catch (Throwable t) {
                errorRef.set(t);
              } finally {
                done.countDown();
              }
            });
    t1.start();
    t2.start();
    // TODO: Adjust await time if CI is slow
    boolean finished = done.await(5, TimeUnit.SECONDS);
    assertEquals((boolean) true, (boolean) finished);
    if (errorRef.get() != null) {
      throw new AssertionError("Concurrent operation threw", errorRef.get());
    }
    // After registration completes, the new factory should be used
    BaseLlm finalInstance = (BaseLlm) LlmRegistry.getLlm(model);
    BaseLlm fromSecond = (BaseLlm) secondFactory.getCreated(model);
    assertSame((BaseLlm) fromSecond, (BaseLlm) finalInstance);
  }

