  @Test
  @Tag("integration")
  @Timeout(10)
  public void testPostOverrideLookupsUseNewFactoryDespiteConcurrentActivity() throws Exception {
    String pattern = "override-.*";
    String model = "override-1";
    // Initial factory and cache
    LlmFactory initialFactory = Mockito.mock(LlmFactory.class);
    BaseLlm initialInstance = (BaseLlm) newLlm("initial-override-1");
    Mockito.when(initialFactory.create(Mockito.eq(model))).thenReturn(initialInstance);
    LlmRegistry.registerTestLlm(pattern, initialFactory);
    CountDownLatch started = new CountDownLatch(1);
    CountDownLatch proceed = new CountDownLatch(1);
    CountDownLatch done = new CountDownLatch(1);
    AtomicReference<Throwable> error = new AtomicReference<>(null);
    Thread actor =
        new Thread(
            () -> {
              try {
                // Create initial cache
                BaseLlm first = (BaseLlm) LlmRegistry.getLlm(model);
                assertSame((BaseLlm) initialInstance, (BaseLlm) first);
                started.countDown();
                // Wait to allow override
                proceed.await(3, TimeUnit.SECONDS); // TODO: adjust await as appropriate
                // After override, accesses should be fine (not verifying here)
                BaseLlm later = (BaseLlm) LlmRegistry.getLlm(model);
                assertNotNull((BaseLlm) later);
              } catch (Throwable t) {
                error.set(t);
              } finally {
                done.countDown();
              }
            });
    actor.start();
    started.await(3, TimeUnit.SECONDS); // TODO: adjust await as appropriate
    // New factory to override
    LlmFactory newFactory = Mockito.mock(LlmFactory.class);
    BaseLlm newInstance = (BaseLlm) newLlm("new-override-1");
    Mockito.when(newFactory.create(Mockito.eq(model))).thenReturn(newInstance);
    // Perform override
    LlmRegistry.registerTestLlm(pattern, newFactory);
    proceed.countDown();
    boolean finished = done.await(5, TimeUnit.SECONDS);
    assertEquals((boolean) true, (boolean) finished);
    if (error.get() != null) {
      throw new AssertionError("Concurrent activity failed", error.get());
    }
    // After override completes, subsequent lookups should use new factory
    BaseLlm after = (BaseLlm) LlmRegistry.getLlm(model);
    assertSame((BaseLlm) newInstance, (BaseLlm) after);
    assertNotSame((BaseLlm) initialInstance, (BaseLlm) after);
  }
