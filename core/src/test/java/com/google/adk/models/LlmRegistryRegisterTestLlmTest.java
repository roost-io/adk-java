  // Helper counting factory for scenario 10
  static class CountingFactory implements LlmRegistry.LlmFactory {

    private final java.util.concurrent.atomic.AtomicInteger counter =
        new java.util.concurrent.atomic.AtomicInteger(0);

    private final Map<String, BaseLlm> responses = new ConcurrentHashMap<>();

    void putResponse(String modelName, BaseLlm llm) {
      responses.put(modelName, llm);
    }

    int getCount() {
      return counter.get();
    }

    @Override
    public BaseLlm create(String modelName) {
      counter.incrementAndGet();
      BaseLlm llm = responses.get(modelName);
      if (llm == null) {
        // TODO: Provide a response for the requested modelName in the test setup
        // if needed.
        throw new IllegalStateException("No configured response for model: " + modelName);
      }
      return llm;
    }
  }
