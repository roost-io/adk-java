  @DisplayName(
      "Scenario 20: After overriding pattern, subsequent creations use the new factory even for names created concurrently before registration completes")
  public void testPostOverrideLookupsUseNewFactoryDespiteConcurrentActivity()
      throws InterruptedException {
    Map<String, BaseLlm> oldMap = new ConcurrentHashMap<>();
    BaseLlm oldInst = Mockito.mock(BaseLlm.class);
    oldMap.put("override-1", oldInst);
    LlmFactory oldFactory = factoryFromMap(oldMap);
    LlmRegistry.registerTestLlm("override-.*", oldFactory);
    CountDownLatch ready = new CountDownLatch(1);
    CountDownLatch proceed = new CountDownLatch(1);
    AtomicReference<BaseLlm> previousRef = new AtomicReference<>();
    ExecutorService pool = Executors.newSingleThreadExecutor();
    pool.submit(
        () -> {
          try {
            ready.countDown();
            proceed.await(5, TimeUnit.SECONDS);
            BaseLlm prev = LlmRegistry.getLlm("override-1");
            previousRef.set(prev);
          } catch (InterruptedException e) {
            Thread.currentThread().interrupt();
          }
        });
    ready.await(5, TimeUnit.SECONDS);
    proceed.countDown();
    // Register new factory
    Map<String, BaseLlm> newMap = new ConcurrentHashMap<>();
    BaseLlm newInst = Mockito.mock(BaseLlm.class);
    newMap.put("override-1", newInst);
    LlmFactory newFactory = factoryFromMap(newMap);
    LlmRegistry.registerTestLlm("override-.*", newFactory);
    pool.shutdown();
    pool.awaitTermination(5, TimeUnit.SECONDS);
    BaseLlm prev = previousRef.get();
    BaseLlm after = LlmRegistry.getLlm("override-1");
    assertNotSame((BaseLlm) prev, (BaseLlm) after);
    assertSame((BaseLlm) newInst, (BaseLlm) after);
  }

